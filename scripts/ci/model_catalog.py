"""One source of truth for model locations and website categories.

The slug remains stable for published Pages URLs, while source directories
are organized by their intended role. Use this module from CI, not copies
of a 10-item path mapping in multiple shell scripts.
"""
from pathlib import Path
import sys

SOURCES = {
    "plate": "models/basic/plate/scpf/model.py",
    "csg-cube": "models/basic/csg-cube/scpf/model.py",
    "bracket": "models/basic/bracket/scpf/model.py",
    "sample-plate": "models/basic/sample-plate/scpf/model.py",
    "plastic-enclosure": "models/basic/plastic-enclosure/scpf/model.py",
    "plastic-enclosure-pi": "models/basic/plastic-enclosure-pi/scpf/model.py",
    "corner-bracket": "models/components/corner_bracket.py",
    "hub75-panel": "models/components/hub75.py",
    "hub75-screen": "models/advanced/hub75-screen/scpf/model.py",
    "hub75-wood-frame": "models/advanced/hub75-wood-frame/scpf/model.py",
}
# Reusable component models are compiled directly from models/components/*.py.
# Assemblies import those exact classes; no SCPF launcher/wrapper file exists
# for the standalone CornerBracket or Hub75Panel.
#
# COMPONENT_SOURCES also tells the result site which advanced models import a
# shared definition. For direct component roots SOURCES and COMPONENT_SOURCES
# intentionally point to the same file.
#
# Independent native-command implementations. Not generated by SCPF at
# runtime: these files contain their own explicit SolidCraft command calls.
# Start with Plate and CornerBracket; expand only after native comparison.
COMMAND_SOURCES = {
    "plate": "models/basic/plate/scpc/model.py",
    "corner-bracket": "models/components/corner-bracket/scpc/model.py",
}

COMPONENT_SOURCES = {
    "corner-bracket": "models/components/corner_bracket.py",
    "hub75-panel": "models/components/hub75.py",
    "hub75-screen": "models/components/hub75.py",
}

# Component examples display their real source first. Assemblies are primarily
# about arranging components, so show the assembly script first.
COMPONENT_DEFINITION_PRIMARY = frozenset({
    "corner-bracket", "hub75-panel",
})

SECTIONS = {
    "basic": ("Basic Models", "Small, transparent models used to develop and verify SCPF features.",
              ("plate", "csg-cube", "bracket", "sample-plate", "plastic-enclosure", "plastic-enclosure-pi")),
    "components": ("Components", "Reusable physical parts compiled directly from the same source assemblies import.",
                   ("corner-bracket", "hub75-panel")),
    "advanced": ("Advanced Models", "Full designs and nested native assemblies built from reusable components.",
                 ("hub75-screen", "hub75-wood-frame")),
}


def source_path(root, slug, language="scpf"):
    if language == "scpf":
        return Path(root) / SOURCES[slug]
    if language == "scpc":
        return Path(root) / COMMAND_SOURCES[slug]
    raise ValueError("language must be scpf or scpc")


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3):
        raise SystemExit("Usage: python scripts/ci/model_catalog.py <model-slug> [scpf|scpc]")
    language = sys.argv[2] if len(sys.argv) == 3 else "scpf"
    table = SOURCES if language == "scpf" else COMMAND_SOURCES if language == "scpc" else {}
    if sys.argv[1] not in table:
        raise SystemExit(f"Unknown {language} model: {sys.argv[1]}")
    print(table[sys.argv[1]])
